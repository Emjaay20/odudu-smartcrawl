import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import { SECTIONS } from './nav';

type SidebarItemConfig = Extract<SidebarsConfig[string], readonly unknown[]>[number];

function section(id: string): (typeof SECTIONS)[number] {
  const found = SECTIONS.find((candidate) => candidate.id === id);
  if (found === undefined) throw new Error(`nav.ts has no section ${id}`);
  return found;
}

function page(id: string): SidebarItemConfig {
  return { type: 'doc' as const, id, label: section(id).label };
}

// A directory of pages beneath a page of its own. Collapsed, so a long list of
// pages never sits in the navigation until the reader is inside it.
function directory(label: string, path: string, items?: SidebarItemConfig[]): SidebarItemConfig {
  return {
    type: 'category' as const,
    label,
    link: { type: 'doc' as const, id: `${path}/index` },
    collapsed: true,
    items: items ?? [{ type: 'autogenerated' as const, dirName: path }],
  };
}

// The recorded transcripts are looked up from the pages that link them, so
// each group is collapsed and the whole is one entry in the reference.
const TRANSCRIPTS = directory('Transcripts', 'reference/transcripts', [
  directory('Request paths', 'reference/transcripts/request-paths'),
  directory('Admin paths', 'reference/transcripts/admin-paths'),
  directory('Console paths', 'reference/transcripts/console-paths'),
]);

// The sidebar follows what a reader is trying to do: start, follow a
// journey, understand, run it, look something up.
export const SIDEBAR_ITEMS: SidebarItemConfig[] = [
  {
    type: 'category' as const,
    label: 'Start here',
    collapsible: false,
    collapsed: false,
    items: [
      directory(section('introduction/index').label, 'introduction'),
      page('quick-start/index'),
    ],
  },
  directory(section('guides/index').label, 'guides'),
  directory(section('concepts/index').label, 'concepts'),
  directory(section('admin-console/index').label, 'admin-console'),
  page('operating/index'),
  {
    type: 'category' as const,
    label: section('reference/index').label,
    link: { type: 'doc' as const, id: 'reference/index' },
    collapsed: true,
    items: [
      { type: 'autogenerated' as const, dirName: 'reference/generated' },
      { type: 'doc' as const, id: 'roadmap', label: 'Roadmap' },
      TRANSCRIPTS,
    ],
  },
  page('security/index'),
  directory(section('contributing/index').label, 'contributing'),
];

const sidebars: SidebarsConfig = { docs: SIDEBAR_ITEMS };

export default sidebars;
