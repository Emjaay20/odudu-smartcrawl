import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import { SECTIONS } from './nav';

const REFERENCE = 'reference/index';

// The reference is the one section with pages beneath it: those the build
// generates from the code, which the sidebar finds by directory.
export const SECTION_ITEMS = SECTIONS.map((section) =>
  section.id === REFERENCE
    ? {
        type: 'category' as const,
        label: section.label,
        link: { type: 'doc' as const, id: section.id },
        collapsed: true,
        items: [{ type: 'autogenerated' as const, dirName: 'reference/generated' }],
      }
    : { type: 'doc' as const, id: section.id, label: section.label },
);

const sidebars: SidebarsConfig = { docs: SECTION_ITEMS };

export default sidebars;
