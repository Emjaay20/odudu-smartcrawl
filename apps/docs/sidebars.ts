import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import { SECTIONS } from './nav';

type SidebarItemConfig = Extract<SidebarsConfig[string], readonly unknown[]>[number];

const REFERENCE = 'reference/index';
const ADMIN_CONSOLE = 'admin-console/index';

// Pages cut from one long document, shown expanded: the section pages are
// reached from the sidebar of their section's page, one click from the home page.
function pagesCategory(label: string, directory: string): SidebarItemConfig {
  return {
    type: 'category' as const,
    label,
    link: { type: 'doc' as const, id: `${directory}/index` },
    collapsed: false,
    items: [{ type: 'autogenerated' as const, dirName: directory }],
  };
}

// Sections with pages beneath them: the reference holds those the build
// generates, which the sidebar finds by directory, and the transcripts of the
// protocol and the admin API; the console's pages sit beneath its tour.
const CHILDREN: Record<string, SidebarItemConfig[]> = {
  [REFERENCE]: [
    { type: 'autogenerated' as const, dirName: 'reference/generated' },
    pagesCategory('Request paths', 'reference/protocol'),
    pagesCategory('Admin paths', 'reference/admin-api-paths'),
  ],
  [ADMIN_CONSOLE]: [pagesCategory('Console paths', 'admin-console/paths')],
};

export const SECTION_ITEMS = SECTIONS.map((section) => {
  const items = CHILDREN[section.id];
  return items === undefined
    ? { type: 'doc' as const, id: section.id, label: section.label }
    : {
        type: 'category' as const,
        label: section.label,
        link: { type: 'doc' as const, id: section.id },
        collapsed: true,
        items,
      };
});

const sidebars: SidebarsConfig = { docs: SECTION_ITEMS };

export default sidebars;
